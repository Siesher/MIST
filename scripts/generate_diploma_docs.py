# ─────────────────────────────────────────────────────────────────────
# Общие хелперы
# ─────────────────────────────────────────────────────────────────────


def add_heading(doc: Document, text: str, level: int = 1) -> None:
    h = doc.add_heading(text, level=level)
    h.alignment = WD_ALIGN_PARAGRAPH.LEFT


def add_para(doc: Document, text: str, first_line_indent: float = 1.25) -> None:
    p = doc.add_paragraph(text)
    p.paragraph_format.first_line_indent = Cm(first_line_indent)
    p.paragraph_format.line_spacing = 1.5
    for run in p.runs:
        run.font.size = Pt(14)


def add_center(doc: Document, text: str, bold: bool = False) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    if bold:
        run.bold = True
    run.font.size = Pt(14)


def add_bullet_list(doc: Document, items: list) -> None:
    for item in items:
        p = doc.add_paragraph(item, style="List Bullet")
        p.paragraph_format.line_spacing = 1.5


def add_numbered_list(doc: Document, items: list) -> None:
    for item in items:
        p = doc.add_paragraph(item, style="List Number")
        p.paragraph_format.line_spacing = 1.5


def add_table(doc: Document, headers: list, rows: list, caption: str = "") -> None:
    if caption:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run(caption).italic = True
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = h
        for p in hdr_cells[i].paragraphs:
            for run in p.runs:
                run.bold = True
    for row_idx, row in enumerate(rows):
        cells = table.rows[row_idx + 1].cells
        for col_idx, v in enumerate(row):
            cells[col_idx].text = str(v)


def add_page_break(doc: Document) -> None:
    doc.add_page_break()


