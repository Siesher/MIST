def add_heading(doc, text: str, level: int = 1) -> None:
    h = doc.add_heading(text, level=level)
    h.alignment = WD_ALIGN_PARAGRAPH.LEFT


def add_para(doc, text: str, indent: float = 1.25) -> None:
    p = doc.add_paragraph(text)
    p.paragraph_format.first_line_indent = Cm(indent)
    p.paragraph_format.line_spacing = 1.5


def add_center(doc, text: str, bold: bool = False) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    if bold:
        run.bold = True
    run.font.size = Pt(14)


def add_bullet(doc, items: list) -> None:
    for item in items:
        p = doc.add_paragraph(item, style="List Bullet")
        p.paragraph_format.line_spacing = 1.5


def add_numbered(doc, items: list) -> None:
    for item in items:
        p = doc.add_paragraph(item, style="List Number")
        p.paragraph_format.line_spacing = 1.5


def add_code(doc, code: str) -> None:
    p = doc.add_paragraph(code)
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.left_indent = Cm(0.5)
    for run in p.runs:
        run.font.name = "Consolas"
        run.font.size = Pt(10)


def add_table(doc, headers, rows, caption=""):
    if caption:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run(caption).italic = True
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    for i, h in enumerate(headers):
        table.rows[0].cells[i].text = h
        for p in table.rows[0].cells[i].paragraphs:
            for run in p.runs:
                run.bold = True
    for r_idx, row in enumerate(rows):
        for c_idx, v in enumerate(row):
            table.rows[r_idx + 1].cells[c_idx].text = str(v)


def add_page_break(doc) -> None:
    doc.add_page_break()


