def set_cell_shading(cell, hex_fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def add_p(
    doc: Document,
    text: str,
    *,
    style: str | None = None,
    bold: bool = False,
    italic: bool = False,
    size: float | None = None,
    color: RGBColor | None = None,
    align: int | None = None,
    space_before: float = 0,
    space_after: float = 4,
    line_spacing: float = 1.15,
):
    p = doc.add_paragraph(style=style) if style else doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    if size is not None:
        run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    return p


def add_runs(doc: Document, parts: list[tuple[str, dict]], *, space_after: float = 4, line_spacing: float = 1.15):
    """Добавляет абзац из нескольких run с разным форматированием.

    Каждый элемент — (text, opts), где opts может содержать bold, italic, color, size.
    """
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    for text, opts in parts:
        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run.font.size = Pt(opts.get("size", 12))
        run.bold = opts.get("bold", False)
        run.italic = opts.get("italic", False)
        if "color" in opts:
            run.font.color.rgb = opts["color"]
    return p


def heading(doc: Document, text: str, level: int = 1, *, color: RGBColor = DARK_GREEN):
    sizes = {1: 18, 2: 14, 3: 12}
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14 if level == 1 else 10)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.keep_with_next = True
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    run.font.size = Pt(sizes.get(level, 12))
    run.bold = True
    run.font.color.rgb = color
    return p


def slide_header(doc: Document, slide_num: str, title: str, duration: str, *, accumulated: str):
    """Цветная плашка-заголовок слайда: '[Слайд N · MM:SS] — Title (∑ MM:SS)'."""
    table = doc.add_table(rows=1, cols=1)
    table.autofit = True
    cell = table.cell(0, 0)
    set_cell_shading(cell, "1F5C2D")
    cell.paragraphs[0].clear()
    p = cell.paragraphs[0]
    pf = p.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    r1 = p.add_run(f"СЛАЙД {slide_num}  ·  ")
    r1.font.name = "Times New Roman"
    r1.font.size = Pt(10)
    r1.font.color.rgb = RGBColor(0xA8, 0xD4, 0x6F)
    r1.bold = True
    r2 = p.add_run(title)
    r2.font.name = "Times New Roman"
    r2.font.size = Pt(13)
    r2.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    r2.bold = True
    r3 = p.add_run(f"   ⏱ {duration}  /  ∑ {accumulated}")
    r3.font.name = "Times New Roman"
    r3.font.size = Pt(10)
    r3.font.color.rgb = RGBColor(0xC4, 0xE0, 0x8F)
    # Spacing after the table
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(4)
    spacer.paragraph_format.space_before = Pt(2)


def section_label(doc: Document, label: str):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.keep_with_next = True
    r = p.add_run(label)
    r.font.name = "Times New Roman"
    r.font.size = Pt(10)
    r.bold = True
    r.font.color.rgb = ACCENT
    r.font.all_caps = True


def speech_block(doc: Document, text: str):
    """Текст для произнесения — крупнее обычного и с увеличенным интерлиньяжем."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(0.4)
    pf.space_after = Pt(6)
    pf.line_spacing = 1.4
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    run.font.size = Pt(13)


def note_block(doc: Document, parts: list[tuple[str, dict]]):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(0.4)
    pf.space_after = Pt(4)
    pf.line_spacing = 1.2
    for text, opts in parts:
        run = p.add_run(text)
        run.font.name = "Times New Roman"
        run.font.size = Pt(opts.get("size", 11))
        run.bold = opts.get("bold", False)
        run.italic = opts.get("italic", False)
        if "color" in opts:
            run.font.color.rgb = opts["color"]


def bullet(doc: Document, text: str, *, level: int = 0):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.left_indent = Cm(0.6 + 0.6 * level)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.2
    run = p.runs[0] if p.runs else p.add_run("")
    run.text = text
    run.font.name = "Times New Roman"
    run.font.size = Pt(11)


