class Difficulty(str, Enum):
    """Task difficulty levels."""
    EASY = "easy"
    MEDIUM = "medium"
    HARD = "hard"
    OLYMPIAD = "olympiad"


class Subject(str, Enum):
    """Subject areas."""
    MATH = "math"
    PROGRAMMING = "programming"


class TutorMove(str, Enum):
    """Types of tutor responses (teaching moves)."""
    SCAFFOLDING = "scaffolding"      # Break into steps, guide
    PROBLEMATIZE = "problematize"    # Ask why/what if
    RECTIFY = "rectify"              # Point out errors
    ENCOURAGE = "encourage"          # Celebrate progress
    HINT = "hint"                    # Give subtle hint
    TELL = "tell"                    # Reveal answer (last resort!)


# ═══════════════════════════════════════════════════════════════════════════
# TASK MODELS
# ═══════════════════════════════════════════════════════════════════════════

class Task(BaseModel):
    """A mathematical or programming task."""
    
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    subject: Subject = Subject.MATH
    topic: str
    subtopic: Optional[str] = None
    difficulty: Difficulty = Difficulty.MEDIUM
    skills: List[str] = Field(default_factory=list)
    
    # Content
    problem: str
    solution: str
    answer: str
    
    # Teaching aids
    hints: List[str] = Field(default_factory=list, max_length=3)
    common_mistakes: List[str] = Field(default_factory=list)
    
    # Metadata
    estimated_time_minutes: int = 10
    created_at: datetime = Field(default_factory=datetime.now)
    
    class Config:
        json_schema_extra = {
            "example": {
                "topic": "derivatives",
                "difficulty": "medium",
                "problem": "Find the derivative of f(x) = x²sin(x)",
                "solution": "Using product rule...",
                "answer": "2x·sin(x) + x²·cos(x)",
                "hints": ["What rule applies to products?", "Remember: (uv)' = u'v + uv'"],
                "skills": ["product_rule", "chain_rule"]
            }
        }


