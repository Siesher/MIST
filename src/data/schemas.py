class StudentProfile(BaseModel):
    """Student profile with learning history."""
    
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: Optional[str] = None
    
    # Knowledge State
    topic_mastery: Dict[str, float] = Field(default_factory=dict)
    skill_mastery: Dict[str, float] = Field(default_factory=dict)
    
    # Learning History
    tasks_attempted: int = 0
    tasks_solved: int = 0
    total_hints_used: int = 0
    
    # Preferences
    preferred_difficulty: Difficulty = Difficulty.MEDIUM
    learning_style: str = "step_by_step"  # visual, examples, step_by_step
    
    # Session State
    current_streak: int = 0
    last_active: datetime = Field(default_factory=datetime.now)
    
    @property
    def success_rate(self) -> float:
        """Calculate overall success rate."""
        if self.tasks_attempted == 0:
            return 0.0
        return self.tasks_solved / self.tasks_attempted
    
    def get_weak_skills(self, threshold: float = 0.5) -> List[str]:
        """Get skills below mastery threshold."""
        return [
            skill for skill, mastery in self.skill_mastery.items()
            if mastery < threshold
        ]


