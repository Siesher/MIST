class ScaffoldingLevel:
    """Progressive scaffolding levels for Socratic tutoring."""

    CONCEPTUAL = "conceptual"  # High-level theoretical questions
    PROCEDURAL = "procedural"  # Step-by-step guidance
    SPECIFIC = "specific"  # Detailed near-answer hints

    @staticmethod
    def get_questions(topic: str, level: str) -> list:
        """Get Socratic questions for topic and scaffolding level."""
        templates = SOCRATIC_QUESTION_TEMPLATES.get(topic, {})
        return templates.get(level, [])

    @staticmethod
    def next_level(current: str) -> str:
        """Get next (more specific) scaffolding level."""
        levels = ["conceptual", "procedural", "specific"]
        try:
            idx = levels.index(current)
            return levels[min(idx + 1, len(levels) - 1)]
        except ValueError:
            return "conceptual"


