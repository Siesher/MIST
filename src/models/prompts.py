def convert_to_russian_notation(latex_expr: str) -> str:
    """
    Преобразование LaTeX выражения в русскую нотацию.

    Args:
        latex_expr: LaTeX выражение с английской нотацией

    Returns:
        LaTeX выражение с русской нотацией
    """
    result = latex_expr

    # Замена LaTeX команд
    for eng, rus in RUSSIAN_LATEX_COMMANDS.items():
        result = result.replace(eng, rus)

    # Замена текстовых функций
    for eng, rus in RUSSIAN_MATH_NOTATION.items():
        # Замена в текстовом контексте (не в LaTeX командах)
        result = result.replace(f"\\text{{{eng}}}", f"\\text{{{rus}}}")
        # Замена в операторном контексте
        result = result.replace(f"\\operatorname{{{eng}}}", f"\\operatorname{{{rus}}}")

    return result


def convert_to_english_notation(russian_expr: str) -> str:
    """
    Преобразование выражения из русской нотации в английскую.

    Полезно для совместимости с английскими LLM и CAS системами.
    """
    result = russian_expr

    # Обратная карта
    reverse_map = {v: k for k, v in RUSSIAN_MATH_NOTATION.items()}

    for rus, eng in reverse_map.items():
        result = result.replace(rus, eng)

    return result


def translate_math_term(term: str, to_russian: bool = True) -> str:
    """Перевод математического термина."""
    if to_russian:
        return MATH_TERMINOLOGY_RU.get(term.lower(), term)
    else:
        reverse_map = {v: k for k, v in MATH_TERMINOLOGY_RU.items()}
        return reverse_map.get(term.lower(), term)


